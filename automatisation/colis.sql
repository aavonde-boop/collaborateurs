--  Crée la table des colis. Aucune donnée existante n'est modifiée.
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.lp24_colis(
  id          bigint generated by default as identity primary key,
  numero      bigint generated always as identity (start 1) unique,  -- #001, #002, …
  nom         text,
  prenom      text,
  email       text,
  taille      text,
  statut      text not null default 'recu' check (statut in ('recu','prevenu','recupere')),
  recu_le     timestamptz not null default now(),
  prevenu_le  date,
  recupere_le timestamptz,
  commentaire text
);
grant select, insert, update, delete on public.lp24_colis to anon, authenticated;
select 'Installé' as resultat;
